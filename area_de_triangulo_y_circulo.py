base = input("Introduce la base del triángulo: ")
altura = input("Introduce la altura del triángulo: ")
area = (float(base) * float(altura)) / 2
print("El área del triángulo es:", area)
radio = input("Introduce el radio de la circunferencia: ")
perimetro = 2 * 3.1416 * float(radio)
print("El perímetro de la circunferencia es:", perimetro)